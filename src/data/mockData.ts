export const formatIDR = (val: number, compact?: boolean): string => {
  if (compact) {
    if (val >= 1000000000) return `IDR ${(val / 1000000000).toFixed(1)}B`;
    if (val >= 1000000) return `IDR ${(val / 1000000).toFixed(1)}M`;
    if (val >= 1000) return `IDR ${(val / 1000).toFixed(0)}K`;
  }
  return `IDR ${Math.round(val).toLocaleString()}`;
};

